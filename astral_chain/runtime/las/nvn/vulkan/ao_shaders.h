// ---- ao_prep.comp
static const char *AO_PREP_GLSL =
"#version 450\n"
"// Ambient occlusion, first step (runtime/vk_ao.c run): the view-space z of target pixel p * scale, one per occlusion\n"
"// texel, through the inverse projection (vk_ao.c AO_SCALE: 2, half resolution). ao.comp then reads this 4-byte image instead of the 8-byte depth-stencil one, which keeps its many scattered\n"
"// reads in cache. 0 marks the sky (cleared depth): no view-space point has z 0 in front of the camera.\n"
"// The replay's viewports have negative heights, so window y grows downwards from ndc y = +1 (as in dlaa_mv.comp).\n"
"layout(local_size_x = 8, local_size_y = 8) in;\n"
"layout(binding = 0) uniform sampler2D depth_tex;\n"
"layout(binding = 1, r32f) uniform writeonly image2D z_out;\n"
"layout(push_constant) uniform P {\n"
"    vec4 inv2, inv3;   // rows 2 and 3 of the inverse projection, row-major\n"
"    vec4 size;         // target width, height, 1 for -1..1 clip depth (0 for 0..1), scale\n"
"} pc;\n"
"\n"
"void main() {\n"
"    ivec2 p = ivec2(gl_GlobalInvocationID.xy);\n"
"    if (p.x >= imageSize(z_out).x || p.y >= imageSize(z_out).y) return;\n"
"    ivec2 q = min(p * int(pc.size.w), ivec2(pc.size.xy) - 1);\n"
"    float d = texelFetch(depth_tex, q, 0).r;\n"
"    float z = 0.0;\n"
"    if (d < 1.0) {\n"
"        vec2 win = vec2(q) + 0.5;\n"
"        vec4 ndc = vec4(win.x / pc.size.x * 2.0 - 1.0, 1.0 - win.y / pc.size.y * 2.0, pc.size.z > 0.5 ? d * 2.0 - 1.0 : d,\n"
"                        1.0);\n"
"        z = dot(pc.inv2, ndc) / dot(pc.inv3, ndc);\n"
"    }\n"
"    imageStore(z_out, p, vec4(z));\n"
"}\n";

// ---- ao_meter.comp
static const char *AO_METER_GLSL =
"#version 450\n"
"// Ambient occlusion (runtime/vk_ao.c run): the light target's typical brightness, for ao_blur.comp to tell surfaces\n"
"// that glow or stand in a strong light from the rest. The light target holds scene light before the game's exposure, so\n"
"// \"bright\" has no fixed value: the same lamp is 0.5 on the night motorway and 40 in a daylit street. One invocation\n"
"// reads a 32x18 grid of bilinear taps and writes the geometric mean of their luminance, which a few very bright\n"
"// texels (the neon itself) hardly move, into a 1x1 image.\n"
"layout(local_size_x = 1) in;\n"
"layout(binding = 0) uniform sampler2D light_tex;\n"
"layout(binding = 1, r32f) uniform writeonly image2D mean_out;\n"
"\n"
"void main() {\n"
"    float sum = 0.0;\n"
"    for (int y = 0; y < 18; y++)\n"
"        for (int x = 0; x < 32; x++) {\n"
"            vec3 c = textureLod(light_tex, (vec2(x, y) + 0.5) / vec2(32.0, 18.0), 0.0).rgb;\n"
"            sum += log(max(dot(c, vec3(0.2126, 0.7152, 0.0722)), 1e-4));\n"
"        }\n"
"    imageStore(mean_out, ivec2(0), vec4(exp(sum / 576.0)));\n"
"}\n";

// ---- ao_src.comp
static const char *AO_SRC_GLSL =
"#version 450\n"
"// Ambient occlusion (runtime/vk_ao.c run): the light the surfaces send out, level 0 of the image ao.comp reads where a\n"
"// surface hides part of another's sky. One texel stands for 2x2 occlusion texels: the light target's average over\n"
"// their pixels (one bilinear tap in the middle of each occlusion texel's pixels), with the game's fog taken out\n"
"// (ao_blur.comp has the formula): the fog is light scattered in front of the surface, which the surface does not send\n"
"// to its neighbours. An occlusion texel of sky (view z 0) counts as dark: the sky's light is the ambient light the\n"
"// occlusion takes away, and it must not leak into the roofs' edges. The fog is computed once, at the middle of the\n"
"// texel with the mean view z of its surfaces.\n"
"// The light target holds the opaque surfaces only when the occlusion runs: what the game draws afterwards (transparent\n"
"// signs, neon tubes, LED panels) sends no light here.\n"
"// Out: .rgb the light, .a the texel's mean view z (0 sky).\n"
"layout(local_size_x = 8, local_size_y = 8) in;\n"
"layout(binding = 0) uniform sampler2D z_tex;       // view z at the occlusion's resolution (ao_prep.comp)\n"
"layout(binding = 1, rgba16f) uniform writeonly image2D src_out;\n"
"layout(binding = 2) uniform sampler2D light_tex;   // bilinear\n"
"layout(binding = 4) uniform samplerCube fog_tex;   // the game's fog cube map; a stand-in without fog\n"
"layout(push_constant) uniform P {  // ao_blur.comp's constants\n"
"    vec4 glow;          // x: light-target pixels per occlusion texel; w: 1 with the game's fog known\n"
"    vec4 curve;\n"
"    vec4 ndc_to_view;   // view x = z * (ndc.x * a + b), view y = z * (ndc.y * c + d)\n"
"    vec4 size;          // light target width, height, the fog's luminance threshold, its factor on bright surfaces\n"
"    vec4 world0, world1, world2;   // .xyz: the rows of the view-to-world rotation\n"
"    vec4 fog;           // start, 1 / range, exponent, colour scale\n"
"} pc;\n"
"\n"
"void main() {\n"
"    ivec2 p = ivec2(gl_GlobalInvocationID.xy), sz = imageSize(src_out);\n"
"    if (p.x >= sz.x || p.y >= sz.y) return;\n"
"    ivec2 zs = textureSize(z_tex, 0);\n"
"    vec3 c = vec3(0.0);\n"
"    float zsum = 0.0, n = 0.0;\n"
"    for (int j = 0; j < 2; j++)\n"
"        for (int i = 0; i < 2; i++) {\n"
"            ivec2 t = min(p * 2 + ivec2(i, j), zs - 1);\n"
"            float tz = texelFetch(z_tex, t, 0).r;\n"
"            if (tz == 0.0) continue;\n"
"            c += textureLod(light_tex, (vec2(t) + 0.5) * pc.glow.x / pc.size.xy, 0.0).rgb;\n"
"            zsum += tz;\n"
"            n += 1.0;\n"
"        }\n"
"    if (n == 0.0) {\n"
"        imageStore(src_out, p, vec4(0.0));\n"
"        return;\n"
"    }\n"
"    float z = zsum / n;\n"
"    c /= n;\n"
"    if (pc.glow.w > 0.5) {\n"
"        vec2 win = (vec2(p) * 2.0 + 1.0) * pc.glow.x;   // the middle of the texel, in light-target pixels\n"
"        vec2 ndc = vec2(win.x / pc.size.x * 2.0 - 1.0, 1.0 - win.y / pc.size.y * 2.0);\n"
"        vec3 pv = z * vec3(ndc.x * pc.ndc_to_view.x + pc.ndc_to_view.y, ndc.y * pc.ndc_to_view.z + pc.ndc_to_view.w, 1.0);\n"
"        vec3 dir = vec3(dot(pc.world0.xyz, pv), dot(pc.world1.xyz, pv), dot(pc.world2.xyz, pv));\n"
"        vec4 cube = textureLod(fog_tex, dir, 0.0);\n"
"        vec3 colour = cube.rgb * pc.fog.w;\n"
"        float f = clamp(pow(clamp((length(pv) - pc.fog.x) * pc.fog.y, 0.0, 1.0), pc.fog.z) * cube.a, 0.0, 1.0);\n"
"        if (pc.size.w != 1.0) {\n"
"            vec3 lit = max(c - colour * f, 0.0) / max(1.0 - f, 1e-3);\n"
"            float h = clamp(dot(lit, vec3(0.2989, 0.587, 0.114)) - pc.size.z, 0.0, 1.0);\n"
"            f = clamp(f * (1.0 + h * (pc.size.w - 1.0)), 0.0, 1.0);\n"
"        }\n"
"        c = max(c - colour * f, 0.0);\n"
"    }\n"
"    imageStore(src_out, p, vec4(min(c * (n * 0.25), vec3(4096.0)), z));\n"
"}\n";

// ---- ao.comp
static const char *AO_GATHER_GLSL =
"#version 450\n"
"// Ambient occlusion, second step (runtime/vk_ao.c run), at the occlusion's resolution (the target's or half of it). Each texel's view-space position comes\n"
"// from ao_prep.comp's z and the projection's scales (a perspective projection: clip w is a multiple of view z, and x and\n"
"// y depend on their own coordinate and z alone, which vk_ao.c checks); the normal from the nearer of its z neighbours\n"
"// on each axis. The horizon is then searched along a few screen directions (slices): in each slice, the highest point\n"
"// seen above the surface on either side, within a world-space radius, bounds the visible arc, and the cosine-weighted\n"
"// visible part of the hemisphere is integrated in closed form over the arc between the two horizons and the normal\n"
"// projected into the slice (horizon-based ambient occlusion, after Jimenez et al. 2016, \"Practical Real-Time\n"
"// Strategies for Accurate Indirect Occlusion\"). Slice angles and step offsets follow a 4x4 pattern that ao_blur.comp\n"
"// averages out. The pattern stays put from frame to frame, with a temporal upscaler too (vk_ao.c has the measurement).\n"
"// Output: .rgb the visibility per colour channel (1 open, 0 enclosed), .a the texel's view z (0 sky) for the\n"
"// depth-aware blur and upsampling.\n"
"//\n"
"// LIT (a specialization constant: the frame's ambient light is known, vk_ao.c frame_light): the light of what hides\n"
"// counts. On each side of a slice the arc between the tangent plane and the horizon is hidden, and the texel sees the\n"
"// surfaces that raised the horizon there instead. The arc's cosine-weighted share (the same closed form, taken\n"
"// between the two angles) is given back in proportion to those surfaces' light over the game's ambient light along\n"
"// the texel's normal, per colour channel and at most whole: next to a lit sign the arc the sign hides keeps its\n"
"// light, and no arc ever counts for more than the open sky it replaced (the light per arc after Mayaux 2018,\n"
"// \"Horizon-Based Indirect Lighting\"). The light is one read of ao_src.comp's image per side, two thirds of the way to\n"
"// the sample that set the horizon, at the level whose texels span the last two thirds of that way: what stands\n"
"// between the texel and its horizon, without the texel's own light. A read per sample that raises the horizon gave\n"
"// the same picture for 0.16 ms more on a 1472x828 scene (Arc 140T). The light counts from pc.lit.z times the ambient\n"
"// light up (an obstacle lit by the same sky is seen from its lit side here, not from the side the texel faces, and\n"
"// gave back most of every contact) and whole 1 / pc.lit.w later.\n"
"// Without LIT the three channels hold the same visibility, and src_tex and amb_tex are stand-ins.\n"
"layout(constant_id = 0) const bool LIT = false;\n"
"layout(local_size_x = 8, local_size_y = 8) in;\n"
"layout(binding = 0) uniform sampler2D z_tex;\n"
"layout(binding = 1, rgba16f) uniform writeonly image2D ao_out;\n"
"layout(binding = 2) uniform sampler2D src_tex;     // ao_src.comp's light with its levels, trilinear\n"
"layout(binding = 3) uniform samplerCube amb_tex;   // one coarse level of the game's ambient cube map\n"
"layout(push_constant) uniform P {\n"
"    vec4 ndc_to_view;   // x = z * (ndc.x * a + b), y = z * (ndc.y * c + d)\n"
"    vec4 size;          // width, height, how many times wider than tall a texel is in view space (1: square), 0\n"
"    vec4 radius;        // world radius, pixels per unit at view distance 1, largest radius in pixels,\n"
"                        // fade distance\n"
"    vec4 steps;         // slices, steps per side, thin (vk_ao.c AO_THIN), 0\n"
"    vec4 lit;           // the ambient light's factor on amb_tex, src_tex's top level, the light over the ambient light\n"
"                        // from which a hidden arc counts, and 1 / the span up to where it counts whole\n"
"    vec4 world0, world1, world2;   // .xyz: the rows of the view-to-world rotation\n"
"} pc;\n"
"\n"
"const float PI = 3.14159265;\n"
"\n"
"vec3 pos_of(vec2 win, float z) {\n"
"    vec2 ndc = vec2(win.x / pc.size.x * 2.0 - 1.0, 1.0 - win.y / pc.size.y * 2.0);\n"
"    return z * vec3(ndc.x * pc.ndc_to_view.x + pc.ndc_to_view.y, ndc.y * pc.ndc_to_view.z + pc.ndc_to_view.w, 1.0);\n"
"}\n"
"\n"
"float z_at(ivec2 q) { return texelFetch(z_tex, clamp(q, ivec2(0), ivec2(pc.size.xy) - 1), 0).r; }\n"
"\n"
"vec3 pos_at(ivec2 q) { return pos_of(vec2(q) + 0.5, z_at(q)); }\n"
"\n"
"// The nearer of two neighbour differences: across an edge the far side belongs to another surface.\n"
"vec3 nearer(vec3 c, vec3 a, vec3 b) {\n"
"    vec3 da = c - a, db = b - c;\n"
"    return abs(da.z) < abs(db.z) ? da : db;\n"
"}\n"
"\n"
"// The cosine-weighted share of a slice between the view direction and the angle h from it (n: the normal's angle).\n"
"float arc(float h, float n, float cn, float sn) { return 0.25 * (-cos(2.0 * h - n) + cn + 2.0 * h * sn); }\n"
"\n"
"// The light of what hides an arc, as the share of the arc it gives back: one read of the light sent out two thirds of\n"
"// the way to the sample that set the horizon (far: its offset in texels, .z its length; the image's level 0 holds 2x2\n"
"// texels), over the ambient light.\n"
"vec3 given_back(ivec2 p, vec3 far, vec3 inv_amb) {\n"
"    vec2 uv = (vec2(p) + 0.5 + far.xy * (2.0 / 3.0)) / pc.size.xy;\n"
"    vec3 ratio = textureLod(src_tex, uv, clamp(log2(max(far.z / 3.0, 1.0)), 0.0, pc.lit.y)).rgb * inv_amb;\n"
"    return clamp((ratio - pc.lit.z) * pc.lit.w, 0.0, 1.0);\n"
"}\n"
"\n"
"void main() {\n"
"    ivec2 p = ivec2(gl_GlobalInvocationID.xy);\n"
"    if (p.x >= int(pc.size.x) || p.y >= int(pc.size.y)) return;\n"
"    float z = z_at(p);\n"
"    if (z == 0.0) {   // the sky\n"
"        imageStore(ao_out, p, vec4(1.0, 1.0, 1.0, 0.0));\n"
"        return;\n"
"    }\n"
"    vec3 P = pos_of(vec2(p) + 0.5, z);\n"
"    float dist = length(P);\n"
"    float fade = clamp(2.0 - 2.0 * dist / pc.radius.w, 0.0, 1.0);   // gone at the fade distance, full at half of it\n"
"    float r_px = min(pc.radius.x * pc.radius.y / abs(z), pc.radius.z);\n"
"    if (fade <= 0.0 || r_px < 1.0) {\n"
"        imageStore(ao_out, p, vec4(1.0, 1.0, 1.0, z));\n"
"        return;\n"
"    }\n"
"    // the normal; window y down is view y up, so the y difference is taken top minus bottom\n"
"    vec3 dx = nearer(P, pos_at(p - ivec2(1, 0)), pos_at(p + ivec2(1, 0)));\n"
"    vec3 dy = nearer(P, pos_at(p + ivec2(0, 1)), pos_at(p - ivec2(0, 1)));\n"
"    vec3 V = -P / dist;\n"
"    vec3 N = normalize(cross(dx, dy));\n"
"    if (dot(N, V) < 0.0) N = -N;\n"
"\n"
"    // 4x4 ordered pattern: slice turn and step offset per texel\n"
"    const float bayer[16] = float[](0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5);\n"
"    float b = bayer[(p.y & 3) * 4 + (p.x & 3)];\n"
"    float turn = (b + 0.5) / 16.0;\n"
"    float jit = fract((b + 0.5) / 16.0 * 7.0);\n"
"\n"
"    // one over the game's ambient light along the normal, the light an open arc stands for\n"
"    vec3 inv_amb = vec3(0.0);\n"
"    if (LIT) {\n"
"        vec3 Nw = vec3(dot(pc.world0.xyz, N), dot(pc.world1.xyz, N), dot(pc.world2.xyz, N));\n"
"        inv_amb = 1.0 / max(pc.lit.x * textureLod(amb_tex, Nw, 0.0).rgb, vec3(1e-4));\n"
"    }\n"
"\n"
"    int slices = int(pc.steps.x), steps = int(pc.steps.y);\n"
"    float R2 = pc.radius.x * pc.radius.x;\n"
"    float vis = 0.0;\n"
"    vec3 back = vec3(0.0);   // the hidden arcs' light given back\n"
"    for (int s = 0; s < slices; s++) {\n"
"        float phi = (float(s) + turn) * PI / float(slices);\n"
"        // The slice's direction is taken in view space; its step in window pixels (y down) is that many times shorter\n"
"        // across where a texel is wider than tall there: with aspect = wide the game draws an ultrawide view into a\n"
"        // 16:9 target, and lengths are counted in heights.\n"
"        vec3 dirV = vec3(cos(phi), -sin(phi), 0.0);\n"
"        vec2 o = vec2(dirV.x / pc.size.z, -dirV.y);\n"
"        vec3 ortho = normalize(dirV - dot(dirV, V) * V);\n"
"        vec3 axis = cross(dirV, V);\n"
"        vec3 pn = N - axis * dot(N, axis) / max(dot(axis, axis), 1e-8);\n"
"        float plen = length(pn);\n"
"        if (plen < 1e-4) continue;\n"
"        float cn = clamp(dot(pn, V) / plen, -1.0, 1.0);\n"
"        float n = sign(dot(pn, ortho)) * acos(cn);\n"
"        float sn = sin(n);\n"
"        // lowest horizons: the tangent plane on either side\n"
"        float lo1 = cos(n + PI * 0.5), lo0 = cos(n - PI * 0.5);\n"
"        float c1 = lo1, c0 = lo0;\n"
"        // per side, the offset of the sample that set the horizon (.xy, in texels) and its length (.z)\n"
"        vec3 far1 = vec3(0.0), far0 = vec3(0.0);\n"
"        for (int i = 0; i < steps; i++) {\n"
"            float t = (float(i) + jit) / float(steps);\n"
"            float len = max(t * t * r_px, 1.0 + float(i));\n"
"            vec2 so = o * len;\n"
"            for (int side = 0; side < 2; side++) {\n"
"                vec2 win = vec2(p) + 0.5 + (side == 0 ? so : -so);\n"
"                if (win.x < 0.0 || win.y < 0.0 || win.x >= pc.size.x || win.y >= pc.size.y) continue;\n"
"                ivec2 sq = ivec2(win);\n"
"                float sz = z_at(sq);\n"
"                if (sz == 0.0) continue;   // the sky hides nothing\n"
"                vec3 H = pos_of(vec2(sq) + 0.5, sz) - P;\n"
"                float h2 = dot(H, H);\n"
"                if (h2 < 1e-8) continue;\n"
"                float ch = dot(H, V) * inversesqrt(h2);\n"
"                // full within 0.7 R, gone at R; \"thin\" times the square of the offset along the view direction\n"
"                // adds to the squared distance: the depth buffer has no thickness, and a thin shape in front of the surface (bars,\n"
"                // a cage) would otherwise hide its sky like a wall (after the thin-occluder compensation in XeGTAO,\n"
"                // XeGTAO.hlsli, XeGTAO_MainPass, which scales the sample offset's view-space depth; no code copied)\n"
"                float dv = dot(H, V);\n"
"                float wt = clamp(2.0 - 2.0 * (h2 + pc.steps.z * dv * dv) / R2, 0.0, 1.0);\n"
"                if (LIT) {\n"
"                    if (side == 0 && mix(lo1, ch, wt) > c1) far1 = vec3(so, len);\n"
"                    if (side == 1 && mix(lo0, ch, wt) > c0) far0 = vec3(-so, len);\n"
"                }\n"
"                if (side == 0) c1 = max(c1, mix(lo1, ch, wt));\n"
"                else c0 = max(c0, mix(lo0, ch, wt));\n"
"            }\n"
"        }\n"
"        float h1 = n + min(acos(c1) - n, PI * 0.5);\n"
"        float h0 = n + max(-acos(c0) - n, -PI * 0.5);\n"
"        float a = 0.25 * (-cos(2.0 * h1 - n) + cn + 2.0 * h1 * sn) + 0.25 * (-cos(2.0 * h0 - n) + cn + 2.0 * h0 * sn);\n"
"        vis += plen * a;   // a slice's share: an open surface sums to 1 over the turns, whatever its slant\n"
"        if (LIT) {\n"
"            // the arc hidden on each side, from the tangent plane to the horizon, and the light of what hides it\n"
"            float hid1 = arc(n + PI * 0.5, n, cn, sn) - arc(h1, n, cn, sn);\n"
"            float hid0 = arc(n - PI * 0.5, n, cn, sn) - arc(h0, n, cn, sn);\n"
"            vec3 lit = vec3(0.0);\n"
"            if (hid1 > 0.002) lit += hid1 * given_back(p, far1, inv_amb);\n"
"            if (hid0 > 0.002) lit += hid0 * given_back(p, far0, inv_amb);\n"
"            back += plen * lit;\n"
"        }\n"
"    }\n"
"    vec3 v = clamp((vec3(vis) + back) / float(slices), 0.0, 1.0);\n"
"    imageStore(ao_out, p, vec4(mix(vec3(1.0), v, fade), z));\n"
"}\n";

// ---- ao_blur.comp
static const char *AO_BLUR_GLSL =
"#version 450\n"
"// Ambient occlusion (runtime/vk_ao.c run): the blur that averages ao.comp's 4x4 pattern out, at the occlusion's own\n"
"// resolution, where it costs a quarter of what it did per pixel of the light target, and the step that turns the\n"
"// visibility into the factor on the light. Each texel averages the 4x4 texels from two before it to one after it, the\n"
"// pattern's span, so every pattern value counts once; the average therefore sits half a texel before the texel on each\n"
"// axis, which ao_apply.frag takes into account. Each texel also counts by how close its view z is to the centre's, 1\n"
"// over the near half of the tolerance, so occlusion stays on its side of a depth edge and a surface that slants away\n"
"// still counts its texels alike.\n"
"// The visibility becomes what is left of the ambient light through a fixed curve (vk_ao.c AO_OPEN, AO_POWER,\n"
"// AO_MULTIBOUNCE): visibilities from \"open\" up are 1, the rest, scaled to 0..1, is raised to \"power\" and lifted by the\n"
"// multi-bounce fit.\n"
"// The factor then takes that occlusion on one part of the pixel only, per colour channel.\n"
"// It spares the game's fog. Astral Chain's opaque fragment shaders end with their distance fog:\n"
"//   t   = pow(clamp((distance to the camera - start) / range, 0, 1), exponent)\n"
"//   f   = t * cube.a * (1 + h * (bright - 1)),   h = clamp(luminance of the lit surface - threshold, 0, 1)\n"
"//   out = mix(lit surface, cube.rgb * scale, f)\n"
"// with cube a small cube map read along the direction from the camera to the surface, in world space. The fog is light\n"
"// scattered in front of the surface, which nothing near that surface hides, and it can be most of a pixel's light with\n"
"// a small f: in a misty street at 20 m, f is 0.03 and the fog's colour 500 times the surface's. Multiplying the whole\n"
"// pixel by the occlusion dug dark, blurred shapes into the mist around every distant object. The same fog is computed\n"
"// here from the texel's view-space position and the light target's pixel the texel stands for, and what is left of\n"
"// that pixel is the surface's light.\n"
"// And, with LIT (a specialization constant: the frame's ambient light is known, vk_ao.c frame_light), it spares what\n"
"// the sky did not give. The game's opaque shaders light a surface with\n"
"//   mask x albedo x ambient(N) + local lights + reflections + what the surface emits\n"
"// where ambient(N) is the ambient cube map read along the normal times a constant of the c5 block. Occlusion hides\n"
"// the sky, so it takes light from the first term and from the reflections of the surroundings. The albedo is not\n"
"// known here, but it is at most ALBEDO, which bounds what the sky gives: the occlusion is taken on\n"
"// min(surface, ALBEDO x ambient(N)) of the pixel. A pixel brighter than the ambient light can explain (a sign, a\n"
"// surface under a lamp) keeps the rest.\n"
"// Without LIT the whole surface takes the occlusion, and it lets go of what glows instead: where the light target is\n"
"// several times its typical brightness (ao_meter.comp), a lit sign, a lamp, a fire's glow on the ground, the\n"
"// visibility goes to 1, so emissive surfaces are not dimmed.\n"
"// Each channel's factor is 1 - (1 - k) x part / pixel, k being what is left of the ambient light: it never goes below\n"
"// the plain occlusion k nor above 1. Where the pixel holds less light than the fog computed here (a surface drawn\n"
"// without fog), the part is 0.\n"
"// The bounce of the gi level (vk_ao.c, vk_rc.c; with LIT and world0.w > 0, which the other levels never set): g, the\n"
"// light the visible surfaces send this one over the ambient light, from rc_resolve.comp's probes in mean_tex, blended\n"
"// to the texel between the 4 probes around it by distance and by how close their view z is to its own (the nearest in\n"
"// depth when none matches). It is capped, scaled and faded out with distance (the probes are least steady far away),\n"
"// and the factor becomes 1 + share x (g - (1 - k)): the part the sky gives gets g of the ambient light on top of what\n"
"// the occlusion leaves. It can then exceed 1 (ao_apply.frag lets it, up to 1 + the cap).\n"
"// In: .rgb the visibility per channel, .a view z (0 sky). Out: .rgb the factor on the light, .a view z (0 sky).\n"
"layout(constant_id = 0) const bool LIT = false;\n"
"const float ALBEDO = 0.9;   // no surface reflects more of the ambient light than this\n"
"layout(local_size_x = 8, local_size_y = 8) in;\n"
"layout(binding = 0) uniform sampler2D ao_tex;\n"
"layout(binding = 1, rgba16f) uniform writeonly image2D ao_out;\n"
"layout(binding = 2) uniform sampler2D light_tex;   // bilinear\n"
"layout(binding = 3) uniform sampler2D mean_tex;    // 1x1; not written with LIT; with LIT at the gi level, g per probe\n"
"                                                   // (.rgb g, .a probe view z)\n"
"layout(binding = 4) uniform samplerCube fog_tex;   // the game's fog cube map; a stand-in without fog\n"
"layout(binding = 5) uniform samplerCube amb_tex;   // one coarse level of the game's ambient cube map; a stand-in\n"
"                                                   // without LIT\n"
"layout(push_constant) uniform P {\n"
"    vec4 glow;          // x: light-target pixels per occlusion texel; y, z: the brightness, in multiples of the typical\n"
"                        // one, where the occlusion starts to fade and where it is gone; w: 1 with the game's fog known\n"
"    vec4 curve;         // open, power, 2 for the view of the occluded part alone (vk_ao.c AC_AO_DEBUG=2) or else the\n"
"                        // albedo of the multi-bounce fit (0: off; vk_ao.c AO_MULTIBOUNCE), the ambient light's\n"
"                        // factor on amb_tex\n"
"    vec4 ndc_to_view;   // view x = z * (ndc.x * a + b), view y = z * (ndc.y * c + d), as in ao.comp\n"
"    vec4 size;          // light target width, height, the fog's luminance threshold, its factor on bright surfaces\n"
"    vec4 world0, world1, world2;   // .xyz: the rows of the view-to-world rotation; .w with LIT at the gi level: the\n"
"                                   // probe spacing in texels (0: no bounce), the cap on g, the strength\n"
"                                   // (glow.y and glow.z then: the distances where the bounce starts to fade and is gone)\n"
"    vec4 fog;           // start, 1 / range, exponent, colour scale\n"
"} pc;\n"
"\n"
"// The view-space position at light-target window position win with view z.\n"
"vec3 view_at(vec2 win, float z) {\n"
"    vec2 ndc = vec2(win.x / pc.size.x * 2.0 - 1.0, 1.0 - win.y / pc.size.y * 2.0);\n"
"    return z * vec3(ndc.x * pc.ndc_to_view.x + pc.ndc_to_view.y, ndc.y * pc.ndc_to_view.z + pc.ndc_to_view.w, 1.0);\n"
"}\n"
"\n"
"vec3 to_world(vec3 v) { return vec3(dot(pc.world0.xyz, v), dot(pc.world1.xyz, v), dot(pc.world2.xyz, v)); }\n"
"\n"
"// The game's fog on a pixel holding light c at view position pv: its share of the pixel, and its colour.\n"
"float fog_of(vec3 pv, vec3 c, out vec3 colour) {\n"
"    vec4 cube = textureLod(fog_tex, to_world(pv), 0.0);\n"
"    colour = cube.rgb * pc.fog.w;\n"
"    float f = clamp(pow(clamp((length(pv) - pc.fog.x) * pc.fog.y, 0.0, 1.0), pc.fog.z) * cube.a, 0.0, 1.0);\n"
"    if (pc.size.w != 1.0) {   // bright surfaces take another amount of fog: from the surface this f leaves\n"
"        vec3 lit = max(c - colour * f, 0.0) / max(1.0 - f, 1e-3);\n"
"        float h = clamp(dot(lit, vec3(0.2989, 0.587, 0.114)) - pc.size.z, 0.0, 1.0);\n"
"        f = clamp(f * (1.0 + h * (pc.size.w - 1.0)), 0.0, 1.0);\n"
"    }\n"
"    return f;\n"
"}\n"
"\n"
"// The view position of the occlusion texel t wherever it is: a texel past the border stands at its own place with the\n"
"// border's z, so the difference to it is never zero.\n"
"vec3 pos_of(ivec2 t, ivec2 size) {\n"
"    return view_at((vec2(t) * pc.glow.x) + 0.5, texelFetch(ao_tex, clamp(t, ivec2(0), size - 1), 0).a);\n"
"}\n"
"\n"
"// The nearer of two neighbour differences: across an edge the far side belongs to another surface (as in ao.comp).\n"
"vec3 nearer(vec3 c, vec3 a, vec3 b) {\n"
"    vec3 da = c - a, db = b - c;\n"
"    return abs(da.z) < abs(db.z) ? da : db;\n"
"}\n"
"\n"
"// g at occlusion texel p of view z: probe i stands at texel i * spacing + spacing / 2 (rc_trace.comp), and this\n"
"// texel's value sits half a texel before its centre (as the blurred visibility), at p. Limit: rc_trace.comp and\n"
"// rc_resolve.comp bring a last probe past the border back to the last texel (a size whose remainder by the spacing is\n"
"// 1 to spacing / 2); its position here is the unbounded one, off by up to spacing / 2 texels on the last two columns or\n"
"// rows.\n"
"vec3 bounce_at(ivec2 p, float z) {\n"
"    int sp = int(pc.world0.w);\n"
"    ivec2 gs = textureSize(mean_tex, 0);\n"
"    vec2 u = (vec2(p) - float(sp / 2) - 0.5) / float(sp);\n"
"    ivec2 i0 = ivec2(floor(u));\n"
"    vec2 f = u - vec2(i0);\n"
"    float tol = (0.04 * abs(z) + 0.05) * 2.0, wsum = 0.0, near = 1e30;\n"
"    vec3 sum = vec3(0.0), nearv = vec3(0.0);\n"
"    for (int y = 0; y < 2; y++)\n"
"        for (int x = 0; x < 2; x++) {\n"
"            vec4 g = texelFetch(mean_tex, clamp(i0 + ivec2(x, y), ivec2(0), gs - 1), 0);\n"
"            // rc_resolve.comp writes finite values; a non-finite one would give NaN even at weight 0\n"
"            if (g.a == 0.0 || any(isnan(g)) || any(isinf(g))) continue;\n"
"            float dz = abs(g.a - z);\n"
"            float w = (x == 0 ? 1.0 - f.x : f.x) * (y == 0 ? 1.0 - f.y : f.y) * clamp(2.0 - 2.0 * dz / tol, 0.0, 1.0);\n"
"            sum += g.rgb * w;\n"
"            wsum += w;\n"
"            if (dz < near) near = dz, nearv = g.rgb;\n"
"        }\n"
"    return max(wsum > 1e-3 ? sum / wsum : nearv, vec3(0.0));\n"
"}\n"
"\n"
"void main() {\n"
"    ivec2 p = ivec2(gl_GlobalInvocationID.xy), size = textureSize(ao_tex, 0);\n"
"    if (p.x >= size.x || p.y >= size.y) return;\n"
"    float z = texelFetch(ao_tex, p, 0).a;\n"
"    if (z == 0.0) {   // the sky\n"
"        imageStore(ao_out, p, vec4(1.0, 1.0, 1.0, 0.0));\n"
"        return;\n"
"    }\n"
"    float tol = 0.04 * abs(z) + 0.05, wsum = 0.0;\n"
"    vec3 sum = vec3(0.0);\n"
"    for (int y = -2; y < 2; y++)\n"
"        for (int x = -2; x < 2; x++) {\n"
"            vec4 a = texelFetch(ao_tex, clamp(p + ivec2(x, y), ivec2(0), size - 1), 0);\n"
"            float w = a.a == 0.0 ? 0.0 : clamp(2.0 - 2.0 * abs(a.a - z) / tol, 0.0, 1.0);\n"
"            sum += a.rgb * w;\n"
"            wsum += w;\n"
"        }\n"
"    vec3 v = sum / wsum;   // the texel itself always counts\n"
"    if (!LIT) {            // the whole surface takes the occlusion: what glows is let go\n"
"        vec2 uv = (vec2(p) + 0.5) * pc.glow.x / vec2(textureSize(light_tex, 0));\n"
"        float lum = dot(textureLod(light_tex, uv, 0.0).rgb, vec3(0.2126, 0.7152, 0.0722));\n"
"        float typical = texelFetch(mean_tex, ivec2(0), 0).r;\n"
"        v = mix(v, vec3(1.0), smoothstep(pc.glow.y * typical, pc.glow.z * typical, lum));\n"
"    }\n"
"    vec3 k = pow(clamp(v / pc.curve.x, 0.0, 1.0), vec3(pc.curve.y));   // what is left of the ambient light\n"
"    bool part_view = pc.curve.z > 1.5;\n"
"    if (!part_view && pc.curve.z > 0.0) {\n"
"        // The surfaces that hide the sky send part of it back; ao.comp counts those darker than the ambient light as\n"
"        // black. The multi-bounce fit of Jimenez et al. 2016 (\"Practical Real-Time Strategies for Accurate Indirect\n"
"        // Occlusion\", its multi-bounce approximation) gives what is left after the bounces when the surroundings have\n"
"        // the albedo rho: ((a k + b) k + c) k, never below k, 1 at k = 1, lifting the deepest occlusion most.\n"
"        float rho = pc.curve.z;\n"
"        vec3 a = vec3(2.0404 * rho - 0.3324), b = vec3(-4.7951 * rho + 0.6417), c3 = vec3(2.7552 * rho + 0.6903);\n"
"        k = max(k, ((k * a + b) * k + c3) * k);\n"
"    }\n"
"    vec3 g = vec3(0.0);\n"
"    bool bounce = LIT && pc.world0.w > 0.0 && !part_view;\n"
"    if (bounce) {   // faded out first: beyond the fade no probe is read and g stays 0 (the open texel stops early)\n"
"        float dist = length(view_at((vec2(p) * pc.glow.x) + 0.5, z));\n"
"        float fade = clamp((pc.glow.z - dist) / (pc.glow.z - pc.glow.y), 0.0, 1.0);\n"
"        if (fade > 0.0) g = min(bounce_at(p, z), vec3(pc.world1.w)) * pc.world2.w * fade;\n"
"    }\n"
"    if (!part_view && min(k.r, min(k.g, k.b)) >= 1.0 && max(g.r, max(g.g, g.b)) <= 0.0) {   // open: nothing to take\n"
"        imageStore(ao_out, p, vec4(1.0, 1.0, 1.0, z));\n"
"        return;\n"
"    }\n"
"    // the light target's pixel this texel stands for (ao_prep.comp), and the surface's part of it\n"
"    ivec2 q = min(p * int(pc.glow.x), ivec2(pc.size.xy) - 1);\n"
"    vec3 pv = view_at(vec2(q) + 0.5, z);\n"
"    vec3 c = texelFetch(light_tex, q, 0).rgb, colour = vec3(0.0);\n"
"    float f = pc.glow.w > 0.5 ? fog_of(pv, c, colour) : 0.0;\n"
"    vec3 part = max(c - colour * f, 0.0);\n"
"    if (LIT) {\n"
"        // the normal, as ao.comp makes it (window y down is view y up), and what the sky gives along it at most\n"
"        vec3 dx = nearer(pv, pos_of(p - ivec2(1, 0), size), pos_of(p + ivec2(1, 0), size));\n"
"        vec3 dy = nearer(pv, pos_of(p + ivec2(0, 1), size), pos_of(p - ivec2(0, 1), size));\n"
"        vec3 N = normalize(cross(dx, dy));\n"
"        if (dot(N, pv) > 0.0) N = -N;\n"
"        vec3 ambient = pc.curve.w * textureLod(amb_tex, to_world(N), 0.0).rgb;\n"
"        part = min(part, ALBEDO * (1.0 - f) * ambient);\n"
"    }\n"
"    vec3 share = clamp(part / max(c, vec3(1e-6)), 0.0, 1.0);\n"
"    imageStore(ao_out, p, vec4(part_view ? share : bounce ? 1.0 + share * (g - (1.0 - k)) : 1.0 - (1.0 - k) * share, z));\n"
"}\n";

